CREATE OR REPLACE FUNCTION public.record_stock_movement(p_inventory_item_id bigint,p_movement_type text,p_quantity numeric,p_unit_cost numeric DEFAULT 0,p_reason text DEFAULT '',p_idempotency_key uuid DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $fn$
DECLARE v_delta numeric(14,3);v_balance numeric(14,3);v_item_id bigint;v_movement_id bigint;
BEGIN
 IF (SELECT auth.uid()) IS NULL OR NOT (SELECT public.is_admin()) THEN RAISE EXCEPTION 'No tenés permisos para registrar stock';END IF;
 IF p_idempotency_key IS NULL OR p_quantity IS NULL OR p_quantity<=0 OR p_unit_cost IS NULL OR p_unit_cost<0 THEN RAISE EXCEPTION 'Cantidad, costo y clave de operación son obligatorios';END IF;
 IF p_movement_type NOT IN ('opening','purchase','return','consumption','waste','adjustment_in','adjustment_out') THEN RAISE EXCEPTION 'Tipo de movimiento inválido';END IF;
 v_delta:=CASE WHEN p_movement_type IN ('consumption','waste','adjustment_out') THEN -p_quantity ELSE p_quantity END;
 SELECT id INTO v_item_id FROM public.inventory_items WHERE id=p_inventory_item_id AND is_active=true FOR UPDATE;
 IF v_item_id IS NULL THEN RAISE EXCEPTION 'El insumo no existe o está inactivo';END IF;
 SELECT id INTO v_movement_id FROM public.stock_movements WHERE idempotency_key=p_idempotency_key;
 IF v_movement_id IS NOT NULL THEN RETURN jsonb_build_object('duplicate',true,'movement_id',v_movement_id);END IF;
 SELECT coalesce(sum(quantity),0) INTO v_balance FROM public.stock_movements WHERE inventory_item_id=p_inventory_item_id;
 IF v_balance+v_delta<0 THEN RAISE EXCEPTION 'Stock insuficiente. Disponible %, solicitado %',v_balance,p_quantity;END IF;
 INSERT INTO public.stock_movements(inventory_item_id,movement_type,quantity,unit_cost,reason,idempotency_key,actor_id)
 VALUES(p_inventory_item_id,p_movement_type,v_delta,p_unit_cost,left(coalesce(p_reason,''),500),p_idempotency_key,(SELECT auth.uid()))
 ON CONFLICT(idempotency_key) DO NOTHING RETURNING id INTO v_movement_id;
 IF v_movement_id IS NULL THEN SELECT id INTO v_movement_id FROM public.stock_movements WHERE idempotency_key=p_idempotency_key;RETURN jsonb_build_object('duplicate',true,'movement_id',v_movement_id);END IF;
 RETURN jsonb_build_object('duplicate',false,'movement_id',v_movement_id,'new_balance',v_balance+v_delta);
END; $fn$;
REVOKE ALL ON FUNCTION public.record_stock_movement(bigint,text,numeric,numeric,text,uuid) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.record_stock_movement(bigint,text,numeric,numeric,text,uuid) TO authenticated,service_role;

CREATE OR REPLACE FUNCTION public.create_purchase_order(p_supplier_id bigint,p_notes text,p_items jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $fn$
DECLARE v_order_id bigint;v_item jsonb;v_inventory_id bigint;v_qty numeric(14,3);v_cost numeric(14,2);v_line numeric(14,2);v_total numeric(14,2):=0;
BEGIN
 IF (SELECT auth.uid()) IS NULL OR NOT (SELECT public.is_admin()) THEN RAISE EXCEPTION 'No tenés permisos para crear compras';END IF;
 IF NOT EXISTS(SELECT 1 FROM public.suppliers WHERE id=p_supplier_id AND is_active=true) THEN RAISE EXCEPTION 'Seleccioná un proveedor activo';END IF;
 IF jsonb_typeof(p_items)<>'array' OR jsonb_array_length(p_items)<1 OR jsonb_array_length(p_items)>50 THEN RAISE EXCEPTION 'La compra debe tener entre 1 y 50 renglones';END IF;
 INSERT INTO public.purchase_orders(supplier_id,status,notes,created_by) VALUES(p_supplier_id,'pending',left(coalesce(p_notes,''),1000),(SELECT auth.uid())) RETURNING id INTO v_order_id;
 FOR v_item IN SELECT value FROM jsonb_array_elements(p_items) LOOP
   v_inventory_id:=(v_item->>'inventory_item_id')::bigint;v_qty:=(v_item->>'quantity')::numeric;v_cost:=(v_item->>'unit_cost')::numeric;
   IF v_qty IS NULL OR v_qty<=0 OR v_cost IS NULL OR v_cost<0 THEN RAISE EXCEPTION 'Revisá cantidad y costo de cada renglón';END IF;
   IF NOT EXISTS(SELECT 1 FROM public.inventory_items WHERE id=v_inventory_id AND is_active=true) THEN RAISE EXCEPTION 'Uno de los insumos no existe o está inactivo';END IF;
   v_line:=round(v_qty*v_cost,2);
   INSERT INTO public.purchase_order_items(purchase_order_id,inventory_item_id,quantity,unit_cost,line_total) VALUES(v_order_id,v_inventory_id,v_qty,v_cost,v_line);
   v_total:=v_total+v_line;
 END LOOP;
 UPDATE public.purchase_orders SET total_amount=v_total,updated_at=now() WHERE id=v_order_id;
 RETURN jsonb_build_object('id',v_order_id,'total_amount',v_total,'status','pending');
END; $fn$;
REVOKE ALL ON FUNCTION public.create_purchase_order(bigint,text,jsonb) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.create_purchase_order(bigint,text,jsonb) TO authenticated,service_role;

CREATE OR REPLACE FUNCTION public.receive_purchase_order(p_purchase_order_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $fn$
DECLARE v_order public.purchase_orders%ROWTYPE;v_line record;v_count integer:=0;
BEGIN
 IF (SELECT auth.uid()) IS NULL OR NOT (SELECT public.is_admin()) THEN RAISE EXCEPTION 'No tenés permisos para recibir compras';END IF;
 SELECT * INTO v_order FROM public.purchase_orders WHERE id=p_purchase_order_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'La compra no existe';END IF;
 IF v_order.status='received' THEN RETURN jsonb_build_object('id',v_order.id,'status','received','duplicate',true);END IF;
 IF v_order.status<>'pending' THEN RAISE EXCEPTION 'Solo se reciben compras pendientes';END IF;
 IF NOT EXISTS(SELECT 1 FROM public.purchase_order_items WHERE purchase_order_id=v_order.id) THEN RAISE EXCEPTION 'La compra no tiene renglones';END IF;
 FOR v_line IN SELECT id,inventory_item_id,quantity,unit_cost FROM public.purchase_order_items WHERE purchase_order_id=v_order.id ORDER BY inventory_item_id,id LOOP
   PERFORM 1 FROM public.inventory_items WHERE id=v_line.inventory_item_id AND is_active=true FOR UPDATE;
   IF NOT FOUND THEN RAISE EXCEPTION 'Uno de los insumos está inactivo';END IF;
   INSERT INTO public.stock_movements(inventory_item_id,movement_type,quantity,unit_cost,reason,reference_type,reference_id,idempotency_key,actor_id)
   VALUES(v_line.inventory_item_id,'purchase',v_line.quantity,v_line.unit_cost,'Recepción de compra #'||v_order.id,'purchase_order',v_order.id::text,md5('purchase-order:'||v_order.id::text||':line:'||v_line.id::text)::uuid,(SELECT auth.uid()))
   ON CONFLICT(idempotency_key) DO NOTHING;
   IF FOUND THEN v_count:=v_count+1;END IF;
 END LOOP;
 UPDATE public.purchase_orders SET status='received',received_at=now(),updated_at=now() WHERE id=v_order.id;
 RETURN jsonb_build_object('id',v_order.id,'status','received','stock_movements_created',v_count);
END; $fn$;
REVOKE ALL ON FUNCTION public.receive_purchase_order(bigint) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.receive_purchase_order(bigint) TO authenticated,service_role;

CREATE OR REPLACE FUNCTION public.consume_recipe_stock_for_order()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $fn$
DECLARE v_need record;v_line record;v_balance numeric(14,3);
BEGIN
 IF NEW.status IS DISTINCT FROM 'preparing' OR OLD.status IS NOT DISTINCT FROM NEW.status THEN RETURN NEW;END IF;
 FOR v_need IN
   SELECT ri.inventory_item_id,sum(oi.quantity*ri.quantity/r.yield_quantity) required_quantity
   FROM public.order_items oi JOIN public.recipes r ON r.product_id=oi.product_id AND r.is_active=true
   JOIN public.recipe_items ri ON ri.recipe_id=r.id WHERE oi.order_id=NEW.id GROUP BY ri.inventory_item_id ORDER BY ri.inventory_item_id
 LOOP
   PERFORM 1 FROM public.inventory_items WHERE id=v_need.inventory_item_id AND is_active=true FOR UPDATE;
   IF NOT FOUND THEN RAISE EXCEPTION 'Una receta usa un insumo inactivo o inexistente';END IF;
   SELECT coalesce(sum(quantity),0) INTO v_balance FROM public.stock_movements WHERE inventory_item_id=v_need.inventory_item_id;
   IF v_balance<v_need.required_quantity THEN RAISE EXCEPTION 'Stock insuficiente para iniciar el pedido %. Insumo %, disponible %, necesario %',NEW.order_number,v_need.inventory_item_id,v_balance,v_need.required_quantity;END IF;
 END LOOP;
 FOR v_line IN
   SELECT oi.id order_item_id,ri.id recipe_item_id,ri.inventory_item_id,oi.quantity*ri.quantity/r.yield_quantity required_quantity,i.default_unit_cost
   FROM public.order_items oi JOIN public.recipes r ON r.product_id=oi.product_id AND r.is_active=true
   JOIN public.recipe_items ri ON ri.recipe_id=r.id JOIN public.inventory_items i ON i.id=ri.inventory_item_id
   WHERE oi.order_id=NEW.id ORDER BY ri.inventory_item_id,oi.id,ri.id
 LOOP
   INSERT INTO public.stock_movements(inventory_item_id,movement_type,quantity,unit_cost,reason,reference_type,reference_id,idempotency_key,actor_id)
   VALUES(v_line.inventory_item_id,'consumption',-v_line.required_quantity,v_line.default_unit_cost,'Consumo por pedido '||coalesce(NEW.order_number,NEW.id::text),'order',NEW.id::text,md5('order:'||NEW.id::text||':line:'||v_line.order_item_id::text||':recipe-item:'||v_line.recipe_item_id::text)::uuid,(SELECT auth.uid()))
   ON CONFLICT(idempotency_key) DO NOTHING;
 END LOOP;
 RETURN NEW;
END; $fn$;
REVOKE ALL ON FUNCTION public.consume_recipe_stock_for_order() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS consume_recipe_stock_for_order_trigger ON public.orders;
CREATE TRIGGER consume_recipe_stock_for_order_trigger AFTER UPDATE OF status ON public.orders FOR EACH ROW EXECUTE FUNCTION public.consume_recipe_stock_for_order();

CREATE OR REPLACE FUNCTION public.create_expense(p_sales_location_id bigint,p_expense_date date,p_category text,p_description text,p_amount numeric,p_payment_method text,p_notes text,p_idempotency_key uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $fn$
DECLARE v_expense_id bigint;v_session_id bigint;
BEGIN
 IF (SELECT auth.uid()) IS NULL OR NOT (SELECT public.is_admin()) THEN RAISE EXCEPTION 'No tenés permisos para registrar gastos';END IF;
 IF p_idempotency_key IS NULL OR p_amount IS NULL OR p_amount<=0 OR p_description IS NULL OR length(btrim(p_description))=0 THEN RAISE EXCEPTION 'Descripción e importe son obligatorios';END IF;
 IF p_payment_method NOT IN ('cash','transfer','debit','credit','other') THEN RAISE EXCEPTION 'Medio de pago inválido';END IF;
 IF NOT EXISTS(SELECT 1 FROM public.sales_locations WHERE id=p_sales_location_id AND is_active=true) THEN RAISE EXCEPTION 'Seleccioná un punto de venta activo';END IF;
 SELECT id INTO v_expense_id FROM public.expenses WHERE idempotency_key=p_idempotency_key;
 IF v_expense_id IS NOT NULL THEN RETURN jsonb_build_object('id',v_expense_id,'duplicate',true);END IF;
 IF p_payment_method='cash' THEN
   SELECT id INTO v_session_id FROM public.cash_sessions WHERE sales_location_id=p_sales_location_id AND status='open' FOR UPDATE;
   IF v_session_id IS NULL THEN RAISE EXCEPTION 'Abrí una caja antes de registrar un gasto en efectivo';END IF;
 END IF;
 INSERT INTO public.expenses(sales_location_id,expense_date,category,description,amount,payment_method,notes,idempotency_key,created_by)
 VALUES(p_sales_location_id,coalesce(p_expense_date,(now() AT TIME ZONE 'America/Argentina/Buenos_Aires')::date),left(coalesce(nullif(btrim(p_category),''),'General'),80),left(btrim(p_description),240),p_amount,p_payment_method,left(coalesce(p_notes,''),1000),p_idempotency_key,(SELECT auth.uid()))
 RETURNING id INTO v_expense_id;
 IF p_payment_method='cash' THEN
   INSERT INTO public.cash_movements(cash_session_id,direction,movement_type,amount,payment_method,reference_type,reference_id,notes,idempotency_key,actor_id)
   VALUES(v_session_id,'out','expense',p_amount,'cash','expense',v_expense_id::text,left(btrim(p_description),240),md5('expense-cash:'||p_idempotency_key::text)::uuid,(SELECT auth.uid()));
 END IF;
 RETURN jsonb_build_object('id',v_expense_id,'duplicate',false);
END; $fn$;
REVOKE ALL ON FUNCTION public.create_expense(bigint,date,text,text,numeric,text,text,uuid) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.create_expense(bigint,date,text,text,numeric,text,text,uuid) TO authenticated,service_role;

