CREATE TABLE IF NOT EXISTS public.customers (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 phone_normalized text NOT NULL UNIQUE,
 phone text NOT NULL,
 name text NOT NULL,
 notes text NOT NULL DEFAULT '',
 tags text[] NOT NULL DEFAULT '{}',
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK (phone_normalized ~ '^[0-9]{8,20}$'),
 CHECK (length(btrim(name)) BETWEEN 1 AND 120)
);
CREATE TABLE IF NOT EXISTS public.inventory_items (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sku text UNIQUE,
 name text NOT NULL,
 category text NOT NULL DEFAULT 'General',
 unit_code text NOT NULL CHECK(unit_code IN ('g','kg','ml','l','unit','pack','portion','other')),
 minimum_stock numeric(14,3) NOT NULL DEFAULT 0 CHECK(minimum_stock>=0),
 default_unit_cost numeric(14,2) NOT NULL DEFAULT 0 CHECK(default_unit_cost>=0),
 is_active boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK(length(btrim(name)) BETWEEN 1 AND 160)
);
CREATE TABLE IF NOT EXISTS public.stock_movements (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inventory_item_id bigint NOT NULL REFERENCES public.inventory_items(id) ON DELETE RESTRICT,
 movement_type text NOT NULL CHECK(movement_type IN ('opening','purchase','return','consumption','waste','adjustment_in','adjustment_out')),
 quantity numeric(14,3) NOT NULL CHECK(quantity<>0),
 unit_cost numeric(14,2) NOT NULL DEFAULT 0 CHECK(unit_cost>=0),
 reason text NOT NULL DEFAULT '',
 reference_type text,
 reference_id text,
 idempotency_key uuid NOT NULL UNIQUE,
 actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS stock_movements_item_created_idx ON public.stock_movements(inventory_item_id,created_at DESC);

CREATE TABLE IF NOT EXISTS public.suppliers (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL CHECK(length(btrim(name)) BETWEEN 1 AND 160),
