DROP POLICY IF EXISTS "Authenticated read categories" ON public.categories;
CREATE POLICY "Public read active categories" ON public.categories FOR SELECT TO anon USING(is_active=true);
CREATE POLICY "Authenticated read categories" ON public.categories FOR SELECT TO authenticated USING(is_active=true OR (SELECT public.is_admin()));
DROP POLICY IF EXISTS "Public read available products" ON public.products;
DROP POLICY IF EXISTS "Authenticated read products" ON public.products;
CREATE POLICY "Public read available products" ON public.products FOR SELECT TO anon USING(is_available=true);
CREATE POLICY "Authenticated read products" ON public.products FOR SELECT TO authenticated USING(is_available=true OR (SELECT public.is_admin()));

