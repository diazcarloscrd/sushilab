-- Keep the admin check at invoker privilege; the admin can see their own mapping through the existing RLS policy.
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean LANGUAGE sql STABLE SECURITY INVOKER SET search_path TO ''
AS $fn$ SELECT EXISTS(SELECT 1 FROM public.admin_users WHERE user_id=(SELECT auth.uid())); $fn$;
REVOKE ALL ON FUNCTION public.is_admin() FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.is_admin() TO authenticated,service_role;

